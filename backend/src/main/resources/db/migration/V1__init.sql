-- BooKI initial schema (PostgreSQL).
--
-- A single baseline. Flyway has only run against throwaway dev/pilot databases,
-- so there is no incremental history worth preserving — the schema is rewritten
-- in place rather than layered with V2/V3. Before deploying a change to this
-- file, wipe the target database (drop all tables incl. flyway_schema_history)
-- so this migration re-runs clean. See ADR-011, ADR-015 and ADR-017.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name          VARCHAR(255) NOT NULL DEFAULT '',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- The user's chosen default reader profile. NULL = fall back to the built-in
    -- "General reader". The FK is added below, once reader_profiles exists.
    default_reader_profile_id BIGINT
);

CREATE TABLE documents (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    title      VARCHAR(500) NOT NULL,
    file_path  VARCHAR(1000) NOT NULL,
    page_count INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE document_pages (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    BIGINT NOT NULL REFERENCES documents (id),
    page_number    INTEGER NOT NULL,
    extracted_text TEXT NOT NULL,
    UNIQUE (document_id, page_number)
);

-- An AI Profile = the "master" a session runs on: persona, difficulty rubrics,
-- per-function prompts, capability routing. Every account is seeded with an
-- editable copy of each shipped template at registration (templates live in
-- the versioned prompt catalog loaded by SlotPromptCatalog, not the DB).
CREATE TABLE ai_profiles (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT NOT NULL REFERENCES users (id),
    name                 VARCHAR(255) NOT NULL,
    based_on_template    VARCHAR(40) NOT NULL,
    is_default           BOOLEAN NOT NULL DEFAULT FALSE,
    enabled_capabilities VARCHAR(120) NOT NULL DEFAULT 'explain,mnemonic,quiz,summary',
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ai_profile_slot_prompts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id    BIGINT NOT NULL REFERENCES ai_profiles (id) ON DELETE CASCADE,
    slot          VARCHAR(40) NOT NULL,
    text          TEXT NOT NULL,
    original_text TEXT NOT NULL,
    UNIQUE (profile_id, slot)
);

-- A Reader Profile = who is reading, in one study context. No link to any AI
-- Profile — a session picks one. user_id NULL marks a shipped, read-only reader
-- template (seeded below); everyone sees those plus their own.
CREATE TABLE reader_profiles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT REFERENCES users (id) ON DELETE CASCADE,
    name         VARCHAR(255) NOT NULL,
    context      TEXT NOT NULL DEFAULT '',
    reader_level VARCHAR(20),
    is_default   BOOLEAN NOT NULL DEFAULT FALSE,
    read_only    BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

