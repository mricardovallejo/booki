-- Per-user default reader profile (see users table). ON DELETE SET NULL so
-- deleting the profile a user had defaulted to just drops them back to the
-- built-in "General reader".
ALTER TABLE users
    ADD CONSTRAINT fk_users_default_reader_profile
    FOREIGN KEY (default_reader_profile_id) REFERENCES reader_profiles (id) ON DELETE SET NULL;

CREATE TABLE sessions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL REFERENCES users (id),
    document_id       BIGINT NOT NULL REFERENCES documents (id),
    start_page        INTEGER NOT NULL,
    end_page          INTEGER NOT NULL,
    current_page      INTEGER NOT NULL,
    ai_profile_id     BIGINT REFERENCES ai_profiles (id) ON DELETE SET NULL,
    reader_profile_id BIGINT REFERENCES reader_profiles (id) ON DELETE SET NULL,
    difficulty        VARCHAR(20) NOT NULL,
    language          VARCHAR(10) NOT NULL DEFAULT 'en',
    ai_provider       VARCHAR(20),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES sessions (id),
    speaker    VARCHAR(20) NOT NULL,
    input_type VARCHAR(20) NOT NULL,
    message    TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tags (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    name       VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tag_documents (
    tag_id      BIGINT NOT NULL REFERENCES tags (id),
    document_id BIGINT NOT NULL REFERENCES documents (id),
    PRIMARY KEY (tag_id, document_id)
);

CREATE TABLE quiz_attempts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    BIGINT NOT NULL REFERENCES sessions (id),
    page_number   INTEGER NOT NULL,
    question      TEXT NOT NULL,
    answer        TEXT NOT NULL,
    difficulty    VARCHAR(20) NOT NULL,
    ai_profile_id BIGINT REFERENCES ai_profiles (id) ON DELETE SET NULL,
    correct       BOOLEAN NOT NULL,
    score         DOUBLE PRECISION NOT NULL,
    feedback      TEXT NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sent_reports (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES sessions (id),
    type       VARCHAR(20) NOT NULL,
    email      VARCHAR(255),
    file_name  VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
